# ================================================================ Markdown 渲染
def render_md(blocks=None):
    """把同一份内容渲染为可编辑的 Markdown 分卷文件，便于后续修改。"""
    blocks = BLOCKS if blocks is None else blocks
    if not os.path.isdir(DOCS_DIR):
        os.makedirs(DOCS_DIR)
    written = []
    current_path = None
    current_title = None
    buf = []

    def flush():
        if current_path is None:
            return
        os.makedirs(os.path.dirname(current_path), exist_ok=True)
        head = '# ' + current_title + '\n\n'
        with open(current_path, 'w', encoding='utf-8') as f:
            f.write(head + '\n'.join(buf).rstrip() + '\n')
        written.append(current_path)

    for blk in blocks:
        kind = blk[0]
        if kind == 'cover' or kind == 'toc':
            continue
        if kind == 'mdnew':
            flush()
            current_path = os.path.join(ROOT, blk[1])
            current_title = blk[2]
            buf = []
            continue
        if current_path is None:
            continue

        if kind == 'h1':
            buf.append('\n## ' + blk[1] + '\n')
        elif kind == 'h2':
            buf.append('\n### ' + blk[1] + '\n')
        elif kind == 'h3':
            buf.append('\n#### ' + blk[1] + '\n')
        elif kind == 'p':
            buf.append(blk[1] + '\n')
        elif kind == 'pn':
            buf.append(blk[1] + '\n')
        elif kind == 'b':
            buf.append('- ' + blk[1] + '\n')
        elif kind == 'table':
            _, headers, rows, widths, caption, size, _keep = blk
            if caption:
                buf.append('**' + caption + '**\n')
            buf.append('| ' + ' | '.join(_md_cell(h) for h in headers) + ' |')
            buf.append('|' + '|'.join(['---'] * len(headers)) + '|')
            for row in rows:
                buf.append('| ' + ' | '.join(_md_cell(c) for c in row) + ' |')
            buf.append('')
        elif kind == 'code':
            buf.append('```')
            buf.append(blk[1])
            buf.append('```\n')
        elif kind == 'center':
            buf.append('> **' + blk[1].replace('\n', ' ') + '**\n')
        elif kind == 'qa':
            _, tag, q, ans = blk
            buf.append('**' + tag + '　' + q + '**\n')
            buf.append('答：' + ans + '\n')
        elif kind == 'pb':
            buf.append('\n---\n')
        elif kind == 'end':
            pass

    flush()
    return written


def _md_cell(v):
    return str(v).replace('\n', '<br>').replace('|', '\\|')


